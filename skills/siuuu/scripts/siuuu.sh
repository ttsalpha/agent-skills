u2=$(( ml * 7 / 10 )); (( u2 <= u1 )) && u2=$(( u1 + 1 ))
u3=$(( ml * 9 / 10 )); (( u3 <= u2 )) && u3=$(( u2 + 1 ))
(( u3 > ml )) && u3=$ml
