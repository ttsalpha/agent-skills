static_mode() {
  local line
  printf '\n'
  for line in "${POSE_SHOUT[@]:2}"; do
    printf '   %s%s%s\n' "$C" "$line" "$R"
  done
  printf '   %s%s%s\n\n' "$C" "$SH0" "$R"
  for line in "${BANNER[@]}"; do
    printf ' %s%s%s\n' "$C" "$line" "$R"
  done
  printf '\n %sSIUUUUUUUUUU!%s 🐐⚽\n\n' "$C" "$R"
}

# Terminal size: stty on stdin (the real tty) — inside $() tput can't see a tty and
# silently falls back to 80x24. SIUUU_TTY (chat mode) overrides; tput is the fallback.
rows='' cols=''
sz=$(stty size 2>/dev/null) || sz=''
if [ -n "${SIUUU_TTY:-}" ]; then
  sz=$(stty size < "$SIUUU_TTY" 2>/dev/null) || sz=''
fi
if [ -n "$sz" ]; then
  rows=${sz%% *}
  cols=${sz##* }
fi
[ -n "$cols" ] || cols=$(tput cols 2>/dev/null || echo 80)
[ -n "$rows" ] || rows=$(tput lines 2>/dev/null || echo 24)
cols=${cols:-80}
rows=${rows:-24}

# --chat (used by the Claude skill, where tool output is captured and can't animate):
# find the terminal Claude Code itself is attached to (walk up the process tree), then
# respawn detached — after Claude's reply streams, the animation plays right on the chat
# screen. A static strip + marker line go to the transcript immediately.
if [ "${1:-}" = '--chat' ] && ! [ -t 1 ]; then
  ttydev=''
  pid=$$
  while [ -n "$pid" ] && [ "$pid" -gt 1 ]; do
    t=$(ps -o tty= -p "$pid" 2>/dev/null | tr -d ' ')
    if [ -n "$t" ] && [ "$t" != '??' ]; then
      ttydev="/dev/$t"
      break
    fi
    pid=$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')
  done
  if [ -n "$ttydev" ] && ( : > "$ttydev" ) 2>/dev/null; then
    SELF=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")
    ( sleep 1; SIUUU_TTY=$ttydev SIUUU_WINCH=$pid bash "$SELF" ) >/dev/null 2>&1 &
    static_mode
    printf '▶ live animation plays right here once Claude goes quiet\n'
    exit 0
  fi
fi

# Not a real terminal (piped, captured by a tool) or too small → static celebration.
if [ "${1:-}" = '--static' ] || ! [ -t 1 ] || [ "$cols" -lt 60 ] || [ "$rows" -lt 22 ]; then
  static_mode
  exit 0
fi

# Geometry adapts to the terminal: sprite box is 12 rows, its bottom row is GROUND,
# the ground shadow sits on GROUND+1 and the banner below that, ending 3 rows above
# the bottom edge so the scene doesn't hug the border. Taller terminal → higher jump.
GROUND=$(( rows - 11 ))
(( GROUND < 16 )) && GROUND=16
ml=$(( GROUND - 12 ))            # max jump lift (sprite top must stay on screen)
(( ml > 10 )) && ml=10
(( ml < 4 )) && ml=4
u1=$(( ml * 2 / 5 )); (( u1 < 1 )) && u1=1
u2=$(( ml * 7 / 10 )); (( u2 <= u1 )) && u2=$(( u1 + 1 ))
u3=$(( ml * 9 / 10 )); (( u3 <= u2 )) && u3=$(( u2 + 1 ))
(( u3 > ml )) && u3=$ml
REGION_TOP=$(( GROUND - 11 - ml ))
(( REGION_TOP < 1 )) && REGION_TOP=1

# Chat mode: wait until Claude Code goes idle (its "Puzzling…" spinner only renders
# while it is generating) so nothing repaints over the show. Capped at ~15s.
if [ -n "${SIUUU_WINCH:-}" ]; then
  i=0
  while [ "$i" -lt 30 ]; do
    cpu=$(ps -o %cpu= -p "$SIUUU_WINCH" 2>/dev/null | tr -d ' ')
    cpu=${cpu%%.*}
    if [ -z "$cpu" ] || [ "$cpu" -lt 2 ]; then
      break
    fi
    sleep 0.5
    i=$(( i + 1 ))
  done
  sleep 0.3
fi

# Alternate screen buffer + hidden cursor; scrollback stays untouched.
printf '\033[?1049h\033[?25l\033[2J'
cleanup() {
  printf '\033[?25h\033[0m\033[?1049l'
  # chat mode: nudge Claude Code (Ink) to fully repaint its UI after we hand
  # the screen back, so nothing is left overlapped or misaligned
  if [ -n "${SIUUU_WINCH:-}" ]; then
    kill -WINCH "$SIUUU_WINCH" 2>/dev/null
  fi
}
trap cleanup EXIT
trap 'exit 130' INT TERM

# draw <top-row> <col> <frame line>...
# Repaints the whole band REGION_TOP..GROUND in one printf (atomic, no flicker). Each line
# gets 4 extra leading spaces drawn at col-4 so a frame fully erases the previous position
# even when advancing 3 columns per step (col must stay >= 5).
draw() {
  local top=$1 col=$2
  shift 2
  local h=$# row i line buf='' dcol=$(( col - 4 ))
  for (( row = REGION_TOP; row <= GROUND; row++ )); do
    if (( row >= top && row < top + h )); then
      i=$(( row - top + 1 ))
      line=${!i}
    else
      line=$BLANK
    fi
    buf+=$'\033['"${row};${dcol}H    ${line}"
  done
  printf '%s%s%s' "$C" "$buf" "$R"
}

# show <lift> <col> <frame line>... — frame plus its ground shadow (narrower when airborne)
show() {
  local lift=$1 col=$2
  shift 2
  draw $(( GROUND - 11 - lift )) "$col" "$@"
  local sh=$SH0
  if (( lift >= 6 )); then sh=$SH3
  elif (( lift >= 3 )); then sh=$SH2
  elif (( lift >= 1 )); then sh=$SH1
  fi
  printf '%s\033[%d;%dH    %s%s' "$C" "$(( GROUND + 1 ))" "$(( col - 4 ))" "$sh" "$R"
}

# Dust trail left behind while running: each puff lives ~0.5s (8 ticks), then is wiped.
TRAIL=()
trail_pop() {
  if (( ${#TRAIL[@]} )); then
    printf '\033[%d;%dH ' "$GROUND" "${TRAIL[0]}"
    if (( ${#TRAIL[@]} > 1 )); then
      TRAIL=( "${TRAIL[@]:1}" )
    else
      TRAIL=()
    fi
  fi
}

# --- run across the screen: legs alternate + 1px bob, dust puffs trailing ---
# stop where the flight (+16 cols) will land the sprite at the screen center
stop=$(( (cols - 36) / 2 - 16 ))
(( stop < 5 )) && stop=5
col=5
f=0
while (( col <= stop )); do
  if (( f % 2 )); then
    show 0 "$col" "${RUN_B[@]}"
    puff='░'
  else
    show 0 "$col" "${RUN_A[@]}"
    puff='▀'
  fi
  printf '%s\033[%d;%dH%s%s' "$DIM$C" "$GROUND" "$(( col - 2 ))" "$puff" "$R"
  TRAIL+=( "$(( col - 2 ))" )
  (( ${#TRAIL[@]} > 8 )) && trail_pop
  f=$(( f + 1 ))
  col=$(( col + 3 ))
  sleep 0.06
done
col=$(( col - 3 ))

# step <lift> <duration> <frame line>... — advance 2 cols, draw one airborne frame
step() {
  local lift=$1 dur=$2
  shift 2
  col=$(( col + 2 ))
  show "$lift" "$col" "$@"
  trail_pop
  sleep "$dur"
}

# --- the jump: crouch → stretch takeoff → 360° spin (fast up, hang at apex, drop fast) ---
show 0 "$col" "${CROUCH[@]}"
trail_pop
sleep 0.18
step "$u1" 0.07 "${STRETCH[@]}"
step "$u2" 0.06 "${SPIN_HALF[@]}"
step "$u3" 0.06 "${SPIN_SLIT[@]}"
step "$ml" 0.09 "${SPIN_BACK_HALF[@]}"
step "$ml" 0.12 "${SPIN_BACK[@]}"
step "$u3" 0.06 "${SPIN_BACK_HALF[@]}"
step "$u2" 0.05 "${SPIN_SLIT[@]}"
step "$u1" 0.05 "${SPIN_HALF[@]}"
(( col > cols - 37 )) && col=$(( cols - 37 ))
while (( ${#TRAIL[@]} )); do trail_pop; done

# debris <rowoff:coloff:text>... — white marks placed relative to (GROUND, col);
# marks inside the sprite box are wiped by the next show(), the rest by a ' ' spec here
debris() {
  local spec dr dc txt
  printf '%s' "$W"
  for spec in "$@"; do
    dr=${spec%%:*}
    dc=${spec#*:}; dc=${dc%%:*}
    txt=${spec##*:}
    printf '\033[%d;%dH%s' "$(( GROUND + dr ))" "$(( col + dc ))" "$txt"
  done
  printf '%s' "$R"
}

# --- landing: impact squash + white debris bursting out from under the feet ---
show 0 "$col" "${IMPACT[@]}"
debris '0:2:▓▒' '0:32:▒▓'
printf '\a'
sleep 0.1
show 0 "$col" "${IMPACT[@]}"
debris '-1:1:▒' '0:-1:░' '-1:34:▒' '0:36:░'
sleep 0.1
show 0 "$col" "${POSE[@]}"
debris '0:-1: ' '0:36: '
debris '-2:-1:░' '-2:36:░' '-1:1:░' '-1:34:░'
sleep 0.12
show 0 "$col" "${POSE[@]}"
debris '-2:-1: ' '-2:36: '
sleep 0.25

# --- SIUUU! banner: centered under the logo (sprite center = col+18, banner is 41 wide) ---
bcol=$(( col - 2 ))
(( bcol > cols - 40 )) && bcol=$(( cols - 40 ))
(( bcol < 1 )) && bcol=1
btop=$(( GROUND + 3 ))
(( btop + 5 > rows )) && btop=$(( rows - 5 ))
(( btop < 1 )) && btop=1

banner() {
  local pre=$1 buf='' i
  for i in 0 1 2 3 4 5; do
    buf+=$'\033['"$(( btop + i ));${bcol}H${BANNER[i]}"
  done
  printf '%s%s%s' "$pre" "$buf" "$R"
}

for i in 0 1 2 3 4 5; do
  printf '%s\033[%d;%dH%s%s' "$C" "$(( btop + i ))" "$bcol" "${BANNER[i]}" "$R"
  sleep 0.05
done
# mouth chomps in sync with the flashing banner: SIU-UU-UU!
for i in 1 2; do
  sleep 0.12
  show 0 "$col" "${POSE[@]}"
  banner "$DIM$C"
  sleep 0.12
  show 0 "$col" "${POSE_SHOUT[@]}"
  banner "$C"
done
sleep 2

# Restore the terminal. On the chat terminal, appending anything would desync the
# Claude Code UI — the WINCH repaint in cleanup() is the whole goodbye there.
trap - EXIT
cleanup
if [ -z "${SIUUU_TTY:-}" ]; then
  printf '%sSIUUUUUUUUUU!%s 🐐⚽\n' "$C" "$R"
fi
