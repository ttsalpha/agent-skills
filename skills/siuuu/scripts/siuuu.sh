# debris <rowoff:coloff:text>... — white marks placed relative to (GROUND, col);
# marks inside the sprite box are wiped by the next show(), the rest by a ' ' spec here
debris() {
  local spec dr dc txt
  printf '%s' "$W"
  for spec in "$@"; do
    dr=${spec%%:*}
    dc=${spec#*:}; dc=${dc%%:*}
    txt=${spec##*:}
    printf '\033[%d;%dH%s' "$(( GROUND + dr ))" "$(( col + dc ))" "$txt"
  done
  printf '%s' "$R"
}

