(( REGION_TOP < 1 )) && REGION_TOP=1

# Chat mode: wait until Claude Code goes idle (its "Puzzling…" spinner only renders
# while it is generating) so nothing repaints over the show. Capped at ~15s.
if [ -n "${SIUUU_WINCH:-}" ]; then
  i=0
  while [ "$i" -lt 30 ]; do
    cpu=$(ps -o %cpu= -p "$SIUUU_WINCH" 2>/dev/null | tr -d ' ')
    cpu=${cpu%%.*}
    if [ -z "$cpu" ] || [ "$cpu" -lt 2 ]; then
      break
    fi
    sleep 0.5
    i=$(( i + 1 ))
  done
  sleep 0.3
fi

# Alternate screen buffer + hidden cursor; scrollback stays untouched.
printf '\033[?1049h\033[?25l\033[2J'
cleanup() {
  sfx_stop
  printf '\033[?25h\033[0m\033[?1049l'
  # chat mode: nudge Claude Code (Ink) to fully repaint its UI after we hand
  # the screen back, so nothing is left overlapped or misaligned
  if [ -n "${SIUUU_WINCH:-}" ]; then
    kill -WINCH "$SIUUU_WINCH" 2>/dev/null
  fi
}
trap cleanup EXIT
trap 'exit 130' INT TERM

# draw <top-row> <col> <frame line>...
# Repaints the whole band REGION_TOP..GROUND in one printf (atomic, no flicker). Each line
# gets 4 extra leading spaces drawn at col-4 so a frame fully erases the previous position
# even when advancing 3 columns per step.
draw() {
  local top=$1 col=$2
  shift 2
  local h=$# row i line buf='' dcol=$(( col - 4 )) cut=0
  # Off the left edge (the walk-on starts at a negative col): pin the paint to column 1 and
  # shave the overhang off each line instead. See CLIPPABLE — these lines are multibyte.
  if (( dcol < 1 )); then
    cut=$(( 1 - dcol ))
    dcol=1
  fi
  for (( row = REGION_TOP; row <= GROUND; row++ )); do
    if (( row >= top && row < top + h )); then
      i=$(( row - top + 1 ))
      line=${!i}
    else
      line=$BLANK
    fi
    line="    $line"
    (( cut )) && line=${line:cut}
    buf+=$'\033['"${row};${dcol}H${line}"
  done
  printf '%s%s%s' "$C" "$buf" "$R"
}

# show <lift> <col> <frame line>... — frame plus its ground shadow (narrower when airborne)
show() {
  local lift=$1 col=$2
  shift 2
  draw $(( GROUND - 11 - lift )) "$col" "$@"
  local sh=$SH0
  if (( lift >= 6 )); then sh=$SH3
  elif (( lift >= 3 )); then sh=$SH2
  elif (( lift >= 1 )); then sh=$SH1
  fi
  local dcol=$(( col - 4 ))
  sh="    $sh"
  if (( dcol < 1 )); then
    sh=${sh:$(( 1 - dcol ))}
    dcol=1
  fi
  printf '%s\033[%d;%dH%s%s' "$C" "$(( GROUND + 1 ))" "$dcol" "$sh" "$R"
}

# Dust trail left behind while running: each puff lives ~0.5s (8 ticks), then is wiped.
TRAIL=()
trail_pop() {
  if (( ${#TRAIL[@]} )); then
    printf '\033[%d;%dH ' "$GROUND" "${TRAIL[0]}"
    if (( ${#TRAIL[@]} > 1 )); then
      TRAIL=( "${TRAIL[@]:1}" )
    else
      TRAIL=()
    fi
  fi
}

# --- run across the screen: legs alternate + 1px bob, dust puffs trailing ---
# stop where the flight (+16 cols) will land the sprite at the screen center
stop=$(( (cols - 36) / 2 - 16 ))
(( stop < 5 )) && stop=5
col=5
f=0

# --- pre-roll: walk the mascot on while the clip builds up ---
# The run is only a handful of frames and its length depends on $cols, far shorter than the
# clip's build-up. The pre-roll burns the difference, stopping once the audio still to play is
# just long enough for the run plus the jump, so the shout lands on the touchdown frame.
#
# Frame cost is measured, never assumed: a headless pty and a real terminal with a big window
# differ by tens of ms per repaint, which over ~50 frames is enough to put the shout in mid-air.
#
# SHOUT_MS is where the clip's RMS jumps. If the shout reads early, suspect the measurement
# below before this offset, and change one at a time — moving both overshoots. Lowering it
# brings the landing earlier onto the shout; raising it makes the shout read earlier still.
SHOUT_MS=${SIUUU_SHOUT_MS:-4220}
LATENCY_MS=50                    # player spawn -> first sample
FRAME_MS=71                      # seed, and the fallback when there is no clock

# Left-edge clipping needs character-indexed substrings; under a non-UTF-8 locale ${x:n} counts
# bytes and would shred the frames, so the walk-on stays on screen there.
CLIPPABLE=0
[ ${#SH0} -eq 36 ] && CLIPPABLE=1

run_frames=$(( (stop - 5) / 3 + 1 ))

lit 0
sfx_start
T0=$(now_ms)

# The jump is the only phase that never reads the clock, so its 9 frames need the fork cost
# backed out of the measurement.
CLOCK_MS=0
if [ -n "$T0" ]; then
  clk0=$(now_ms)
  now_ms >/dev/null; now_ms >/dev/null; now_ms >/dev/null; now_ms >/dev/null
  CLOCK_MS=$(( ($(now_ms) - clk0) / 4 ))
  (( CLOCK_MS < 0 )) && CLOCK_MS=0
fi

# Seeded out here because a muted run skips the pre-roll and the run loop still reads both.
done_f=0 fc=$FRAME_MS
JUMP_EST=$(( 740 + 9 * (fc - CLOCK_MS - 60) ))

if [ -n "$PLAYER" ]; then
  # Fixed distance — the loop cannot know its own length up front. 34 and not the full 41 that
  # puts the sprite completely off-screen: the art is 36 wide, so at col -36 every glyph sits
  # left of column 1 and the quadratic below takes ~31% of the pre-roll to drag the first one
  # into view. That read as the screen having hung. Starting at -29 shows a sliver immediately.
  d=0
  (( CLIPPABLE )) && d=34
  while :; do
    if [ -n "$T0" ]; then
      el=$(( $(now_ms) - T0 ))
      (( done_f > 2 )) && fc=$(( el / done_f ))
      (( fc < 62 )) && fc=62
      (( fc > 250 )) && fc=250
    else
      el=$(( done_f * fc ))      # no clock: fall back to the seeded estimate
    fi
    fr=$(( fc - CLOCK_MS ))
    (( fr < 60 )) && fr=60
    JUMP_EST=$(( 740 + 9 * (fr - 60) ))
    # LATENCY_MS is added, not subtracted: the audio starts that much after T0, so the touchdown
    # being aimed at sits later too. Run frames cost fc, since the run reads the clock as well.
    left=$(( SHOUT_MS + LATENCY_MS - JUMP_EST - run_frames * fc - el ))
    (( left < fc )) && break
    p=$(( 100 * el / (el + left) ))   # time-based, so re-estimating never makes the sprite jump
    lit "$p"
    col=$(( 5 - d + d * p * p / 10000 ))   # quadratic ease-in
    if (( f % 2 )); then
      show 0 "$col" "${RUN_B[@]}"
    else
      show 0 "$col" "${RUN_A[@]}"
    fi
    f=$(( f + 1 ))
    done_f=$(( done_f + 1 ))
    sleep 0.06
  done
fi
lit 100
col=5

# The run re-times itself the same way, which is what soaks up both the pre-roll's leftover
# slack and its overestimate of the run (pre-roll frames pay for left-edge clipping; run frames
# never do, and that bias grew with run length). OV is what a frame costs beyond its sleep.
OV=$(( fc - 60 ))
(( OV < 0 )) && OV=0
run_left=$run_frames

while (( col <= stop )); do
  if (( f % 2 )); then
    show 0 "$col" "${RUN_B[@]}"
    puff='░'
  else
    show 0 "$col" "${RUN_A[@]}"
    puff='▀'
  fi
  printf '%s\033[%d;%dH%s%s' "$DIM$C" "$GROUND" "$(( col - 2 ))" "$puff" "$R"
  TRAIL+=( "$(( col - 2 ))" )
  (( ${#TRAIL[@]} > 8 )) && trail_pop
  f=$(( f + 1 ))
  col=$(( col + 3 ))
  run_left=$(( run_left - 1 ))
  nap=60
  if [ -n "$PLAYER" ] && [ -n "$T0" ]; then
    # run_left is already decremented, so the sleeps still to come — this one included — is +1.
    # Dividing by run_left alone overpays every frame and starves the last one to the floor.
    nap=$(( (SHOUT_MS + LATENCY_MS - JUMP_EST - ($(now_ms) - T0)) / (run_left + 1) - OV ))
    (( nap < 10 )) && nap=10       # already late: run as fast as the frames allow
    (( nap > 250 )) && nap=250
  fi
  printf -v napf '%03d' "$nap"     # -v avoids the subshell a $( ) here would fork
  sleep "0.$napf"
done
col=$(( col - 3 ))

# step <lift> <duration> <frame line>... — advance 2 cols, draw one airborne frame
step() {
  local lift=$1 dur=$2
  shift 2
  col=$(( col + 2 ))
  show "$lift" "$col" "$@"
  trail_pop
  sleep "$dur"
}

