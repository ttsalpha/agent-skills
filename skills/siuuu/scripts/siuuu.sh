#!/bin/bash
# siuuu.sh — the Claude Code logo runs up and hits CR7's "Siuuu" celebration.
# Sprite frames are rasterized from claudecode-color.svg (24x24 viewBox, 0.75-unit
# pixels) into 36-col x 12-row half-block frames (▀▄█). All frame lines are exactly
# 36 display columns — never re-pad them with printf width specifiers (multibyte).
# Pure bash + ANSI escapes; macOS /bin/bash 3.2 compatible.
set -u

# Set by --chat's background respawn: bind stdout to the terminal Claude Code runs on,
# so the animation plays right on the chat screen (alt buffer, restored afterwards).
if [ -n "${SIUUU_TTY:-}" ] && ( : > "$SIUUU_TTY" ) 2>/dev/null; then
  exec > "$SIUUU_TTY"
fi

TRUECOLOR=0
if [ -t 1 ]; then
  if [ "${COLORTERM:-}" = 'truecolor' ] || [ "${COLORTERM:-}" = '24bit' ]; then
    TRUECOLOR=1
    C=$'\033[38;2;217;119;87m'   # Claude orange #D97757
  else
    C=$'\033[38;5;173m'
  fi
  DIM=$'\033[2m'
  W=$'\033[1;97m'   # bright white (landing debris)
  R=$'\033[0m'
else
  C='' DIM='' W='' R=''
fi

# lit <0..100> — slides $C from a barely-lit ember up to full Claude orange. Everything reads
# $C at print time, so nothing else has to know the lights are coming up.
CRAMP=(52 88 130 166 172 173)   # 256-colour fallback: dark red -> orange
lit() {
  [ -n "$R" ] || return 0
  local p=$1
  if (( TRUECOLOR )); then
    C=$'\033[38;2;'"$(( 34 + 183 * p / 100 ));$(( 18 + 101 * p / 100 ));$(( 14 + 73 * p / 100 ))"m
  else
    C=$'\033[38;5;'"${CRAMP[$(( p * 6 / 101 ))]}"m
  fi
}

# ---- sound ----
# One pre-mixed take in assets/: ~4.2s of build-up, then the "SIUUU". It is fired once,
# before the run, and the pre-roll below stretches the visuals so the shout lands on the
# touchdown frame. Set SIUUU_SOUND=0 to mute.
#
# Swapping the clip: mono 16-bit PCM WAV is the only format afplay/paplay/aplay all read.
#   ffmpeg -i in.m4a -af "pan=mono|c0=0.5*c0+0.5*c1,alimiter=limit=0.95" \
#          -ar 22050 -c:a pcm_s16le assets/siuuu.wav
# Then re-measure where the shout starts and update SHOUT_MS below, or it will desync.
SIUUU_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SFX=$SIUUU_DIR/assets/siuuu.wav
PLAYER='' SFX_PID=''
if [ "${SIUUU_SOUND:-1}" != '0' ] && [ -r "$SFX" ]; then
  for p in afplay paplay aplay ffplay mpv; do
    if command -v "$p" >/dev/null 2>&1; then PLAYER=$p; break; fi
  done
fi

# The '&' binds to the player itself (not a subshell), so $! is the pid we can actually kill.
sfx_start() {
  [ -n "$PLAYER" ] || return 0
  case $PLAYER in
    ffplay) ffplay -nodisp -autoexit -loglevel quiet "$SFX" >/dev/null 2>&1 & ;;
    mpv)    mpv --no-video --really-quiet "$SFX" >/dev/null 2>&1 & ;;
    *)      "$PLAYER" "$SFX" >/dev/null 2>&1 & ;;
  esac
  SFX_PID=$!
}

# Millisecond clock — bash 3.2 has neither EPOCHREALTIME nor a sub-second $SECONDS. The ~5ms
# perl fork is absorbed because whole frames are what gets measured. Empty output = no clock.
now_ms() { perl -MTime::HiRes -e 'printf "%d", Time::HiRes::time()*1000' 2>/dev/null; }

sfx_stop() {
  [ -n "$SFX_PID" ] && kill "$SFX_PID" 2>/dev/null
  SFX_PID=''
}

