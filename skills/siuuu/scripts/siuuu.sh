# Terminal size: stty on stdin (the real tty) — inside $() tput can't see a tty and
# silently falls back to 80x24. SIUUU_TTY (chat mode) overrides; tput is the fallback.
rows='' cols=''
sz=$(stty size 2>/dev/null) || sz=''
if [ -n "${SIUUU_TTY:-}" ]; then
  sz=$(stty size < "$SIUUU_TTY" 2>/dev/null) || sz=''
fi
if [ -n "$sz" ]; then
  rows=${sz%% *}
  cols=${sz##* }
fi
[ -n "$cols" ] || cols=$(tput cols 2>/dev/null || echo 80)
[ -n "$rows" ] || rows=$(tput lines 2>/dev/null || echo 24)
cols=${cols:-80}
rows=${rows:-24}

# --chat (used by the Claude skill, where tool output is captured and can't animate):
# find the terminal Claude Code itself is attached to (walk up the process tree), then
# respawn detached — after Claude's reply streams, the animation plays right on the chat
# screen. A static strip + marker line go to the transcript immediately.
if [ "${1:-}" = '--chat' ] && ! [ -t 1 ]; then
  ttydev=''
  pid=$$
  while [ -n "$pid" ] && [ "$pid" -gt 1 ]; do
    t=$(ps -o tty= -p "$pid" 2>/dev/null | tr -d ' ')
    if [ -n "$t" ] && [ "$t" != '??' ]; then
      ttydev="/dev/$t"
      break
    fi
    pid=$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')
  done
  if [ -n "$ttydev" ] && ( : > "$ttydev" ) 2>/dev/null; then
    SELF=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")
    (
      sleep 1
      SIUUU_TTY=$ttydev SIUUU_WINCH=$pid SIUUU_SOUND=${SIUUU_SOUND:-1} bash "$SELF"
    ) >/dev/null 2>&1 &
    static_mode
    printf '▶ live animation plays right here once Claude goes quiet\n'
    exit 0
  fi
fi

# Not a real terminal (piped, captured by a tool) or too small → static celebration.
if [ "${1:-}" = '--static' ] || ! [ -t 1 ] || [ "$cols" -lt 60 ] || [ "$rows" -lt 22 ]; then
  # Only on a real terminal — piped/captured output should stay silent. The --chat
  # foreground path exited above, so its background child is the only one that plays.
  [ -t 1 ] && sfx_start
  static_mode
  exit 0
fi

# Geometry adapts to the terminal: sprite box is 12 rows, its bottom row is GROUND,
# the ground shadow sits on GROUND+1 and the banner below that, ending 3 rows above
# the bottom edge so the scene doesn't hug the border. Taller terminal → higher jump.
GROUND=$(( rows - 11 ))
(( GROUND < 16 )) && GROUND=16
ml=$(( GROUND - 12 ))            # max jump lift (sprite top must stay on screen)
(( ml > 10 )) && ml=10
(( ml < 4 )) && ml=4
